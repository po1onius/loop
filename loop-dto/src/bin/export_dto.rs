use std::{fs, io, path::PathBuf};

use loop_dto::{
    CommunityPostReactionResp, CommunityPostResp, CommunityPostType, CommunitySectionResp,
    CompleteMediaUploadResp, ConversationCapabilitiesResp, ConversationKind,
    ConversationMessageResp, ConversationResp, CreateCommunityPostRequest, CreateEventDraftRequest,
    CreateEventRequest, CreateMediaUploadRequest, CreateMediaUploadResp, CurrentUserResp,
    EventContentBlock, EventContentDoc, EventContentImage, EventFeatureBlock, EventInlineNode,
    EventJoinRequestResp, EventJoinReviewDecision, EventParticipationResp,
    EventParticipationStateResp, EventParticipationStatus, EventResp, EventStatus, EventTextColor,
    EventTextMark, ListCommunityPostsResp, ListConversationMessagesResp, ListConversationsResp,
    ListEventJoinRequestsResp, ListEventsResp, LoginRequest, LoginResp,
    MarkConversationReadRequest, MediaAssetResp, MediaDownloadUrlResp, PresignedHeader,
    RefreshTokenRequest, RegisterRequest, ReviewEventJoinRequest, SendConversationMessageRequest,
    SetConversationSubscriptionRequest, SetTokenRequest, UpdateCommunityPostRequest,
    UpdateEventDraftRequest, UpdateUserAvatarRequest, VerifyCodeRequest, VerifyCodeResp,
};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let export_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("loop-dto should be under repo root")
        .join("app")
        .join("lib");

    let cfg = Config::new().with_out_dir(export_dir);
    let mut declarations = Vec::new();

    append::<CreateEventRequest>(&cfg, &mut declarations)?;
    append::<CreateEventDraftRequest>(&cfg, &mut declarations)?;
    append::<UpdateEventDraftRequest>(&cfg, &mut declarations)?;
    append::<CreateMediaUploadRequest>(&cfg, &mut declarations)?;
    append::<CreateMediaUploadResp>(&cfg, &mut declarations)?;
    append::<CompleteMediaUploadResp>(&cfg, &mut declarations)?;
    append::<EventContentBlock>(&cfg, &mut declarations)?;
    append::<EventContentDoc>(&cfg, &mut declarations)?;
    append::<EventContentImage>(&cfg, &mut declarations)?;
    append::<EventFeatureBlock>(&cfg, &mut declarations)?;
    append::<EventInlineNode>(&cfg, &mut declarations)?;
    append::<EventJoinRequestResp>(&cfg, &mut declarations)?;
    append::<EventJoinReviewDecision>(&cfg, &mut declarations)?;
    append::<EventParticipationResp>(&cfg, &mut declarations)?;
    append::<EventParticipationStateResp>(&cfg, &mut declarations)?;
    append::<EventParticipationStatus>(&cfg, &mut declarations)?;
    append::<EventResp>(&cfg, &mut declarations)?;
    append::<EventStatus>(&cfg, &mut declarations)?;
    append::<EventTextColor>(&cfg, &mut declarations)?;
    append::<EventTextMark>(&cfg, &mut declarations)?;
    append::<ListEventsResp>(&cfg, &mut declarations)?;
    append::<ListEventJoinRequestsResp>(&cfg, &mut declarations)?;
    append::<LoginRequest>(&cfg, &mut declarations)?;
    append::<LoginResp>(&cfg, &mut declarations)?;
    append::<CurrentUserResp>(&cfg, &mut declarations)?;
    append::<UpdateUserAvatarRequest>(&cfg, &mut declarations)?;
    append::<MediaAssetResp>(&cfg, &mut declarations)?;
    append::<MediaDownloadUrlResp>(&cfg, &mut declarations)?;
    append::<PresignedHeader>(&cfg, &mut declarations)?;
    append::<RefreshTokenRequest>(&cfg, &mut declarations)?;
    append::<RegisterRequest>(&cfg, &mut declarations)?;
    append::<ReviewEventJoinRequest>(&cfg, &mut declarations)?;
    append::<SetTokenRequest>(&cfg, &mut declarations)?;
    append::<VerifyCodeRequest>(&cfg, &mut declarations)?;
    append::<VerifyCodeResp>(&cfg, &mut declarations)?;
    append::<CommunityPostType>(&cfg, &mut declarations)?;
    append::<ConversationKind>(&cfg, &mut declarations)?;
    append::<CommunitySectionResp>(&cfg, &mut declarations)?;
    append::<CommunityPostResp>(&cfg, &mut declarations)?;
    append::<ListCommunityPostsResp>(&cfg, &mut declarations)?;
    append::<CreateCommunityPostRequest>(&cfg, &mut declarations)?;
    append::<UpdateCommunityPostRequest>(&cfg, &mut declarations)?;
    append::<CommunityPostReactionResp>(&cfg, &mut declarations)?;
    append::<ConversationCapabilitiesResp>(&cfg, &mut declarations)?;
    append::<ConversationResp>(&cfg, &mut declarations)?;
    append::<ListConversationsResp>(&cfg, &mut declarations)?;
    append::<ConversationMessageResp>(&cfg, &mut declarations)?;
    append::<ListConversationMessagesResp>(&cfg, &mut declarations)?;
    append::<SendConversationMessageRequest>(&cfg, &mut declarations)?;
    append::<MarkConversationReadRequest>(&cfg, &mut declarations)?;
    append::<SetConversationSubscriptionRequest>(&cfg, &mut declarations)?;

    let dto_path = cfg.out_dir().join("dto.ts");
    let mut output = String::from(
        "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n",
    );
    output.push('\n');
    output.push_str(&declarations.join("\n\n"));
    output.push('\n');
    fs::write(&dto_path, output).map_err(|err| {
        io::Error::new(
            err.kind(),
            format!("failed to write {}: {err}", dto_path.display()),
        )
    })?;

    Ok(())
}

fn append<T: TS + 'static>(
    cfg: &Config,
    declarations: &mut Vec<String>,
) -> Result<(), Box<dyn std::error::Error>> {
    let generated = T::export_to_string(cfg)?;
    let (_header, declaration) = generated.split_once("\n\n").ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidData,
            "generated TypeScript binding is missing declaration separator",
        )
    })?;
    declarations.push(declaration.trim().to_string());
    Ok(())
}
